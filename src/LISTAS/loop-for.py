## ====================================== FOR - LOOP ======================================

cores = ['verde', 'amarelo', 'azul', 'branco']

for cor in cores: # Imprime cada cor na lista
    print(cor)

for numero in range(1, 11): # Imprime os números de 1 a 10
    print(numero)

for numero in range(1, 11, 2): # Imprime os números de 1 a 10, pulando de 2 em 2
    print(numero)